// Downloads KanjiVG stroke-order data for every kana used by the app and
// writes it to ../strokes.js so the app works fully offline.
// KanjiVG (c) Ulrich Apel, CC BY-SA 3.0 - https://kanjivg.tagaini.net
// Run with: node tools/build-strokes.mjs

import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const here = path.dirname(fileURLToPath(import.meta.url));

// Pull the kanji list straight from kanji.js so the two never drift apart.
const kanjiSrc = await readFile(path.join(here, '..', 'kanji.js'), 'utf8');
const ctx = {};
vm.runInNewContext(kanjiSrc + '\nthis.KANJI = KANJI;', ctx);
const KANJI_CHARS = Object.values(ctx.KANJI).flat().map((k) => k[0]);

const HIRA =
  'あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん' +
  'がぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽゃゅょっ';
const toKata = (s) =>
  [...s].map((ch) => String.fromCodePoint(ch.codePointAt(0) + 0x60)).join('');
const chars = [...new Set([...HIRA, ...toKata(HIRA), 'ー', ...KANJI_CHARS])];

const out = {};
const missing = [];

async function fetchChar(ch) {
  const hex = ch.codePointAt(0).toString(16).padStart(5, '0');
  const urls = [
    `https://cdn.jsdelivr.net/gh/KanjiVG/kanjivg@master/kanji/${hex}.svg`,
    `https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/${hex}.svg`,
  ];
  let svg = null;
  let lastErr = '';
  for (let attempt = 0; attempt < 3 && !svg; attempt++) {
    for (const url of urls) {
      try {
        const res = await fetch(url);
        if (res.ok) { svg = await res.text(); break; }
        lastErr = `${res.status}`;
      } catch (e) {
        lastErr = e.message;
      }
    }
  }
  if (!svg) throw new Error(`${lastErr} for ${ch} (${hex})`);
  // Stroke paths, in drawing order (ids end in -s1, -s2, ...)
  const strokes = [];
  for (const m of svg.matchAll(/<path[^>]*id="kvg:[0-9a-f]+-s(\d+)"[^>]*\sd="([^"]+)"/g)) {
    strokes.push([Number(m[1]), m[2]]);
  }
  strokes.sort((a, b) => a[0] - b[0]);
  // Stroke number label positions
  const nums = [];
  for (const m of svg.matchAll(/<text transform="matrix\(1 0 0 1 ([\d.]+) ([\d.]+)\)">(\d+)<\/text>/g)) {
    nums.push([Number(m[1]), Number(m[2])]);
  }
  if (!strokes.length) throw new Error(`no strokes for ${ch}`);
  return { s: strokes.map((x) => x[1]), n: nums };
}

for (const ch of chars) {
  try {
    out[ch] = await fetchChar(ch);
    process.stdout.write(ch);
  } catch (e) {
    missing.push(`${ch}: ${e.message}`);
  }
}

const js =
  '// Generated by tools/build-strokes.mjs from KanjiVG (c) Ulrich Apel, CC BY-SA 3.0.\n' +
  '// https://kanjivg.tagaini.net - do not edit by hand.\n' +
  'window.STROKES = ' + JSON.stringify(out) + ';\n';
await writeFile(path.join(here, '..', 'strokes.js'), js, 'utf8');

console.log(`\nWrote ${Object.keys(out).length} characters.`);
if (missing.length) console.log('Missing:\n' + missing.join('\n'));
